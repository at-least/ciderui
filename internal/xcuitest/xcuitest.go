// Package xcuitest is Safari on an iOS simulator opening a URL while XCUITest takes
// steps one after another: a label, the element it names tapped, a touch of the
// simulator's screen through its HID, as a finger's (where WebDriver's taps never
// click, reference/popover/); press:<label>, the element held a second;
// type:<text>, the text typed by XCUITest's keyboard into what has the focus: after
// each it waits for the page's "reported N", the page's own report of what the step
// left, which the probe's server keeps. On a simulator of the run's own, of the
// device type given, created on the newest iOS runtime that has it (iOS 27.1's, on
// the Mac since 2026-10-22, has an iPhone Duo alone) and deleted after (the booted
// ones are others'); its UI test generated by XcodeGen from
// reference/xcuitest/project.yml into a temporary directory. Safari's tip over the
// page on a new simulator is closed first (reference/xcuitest/UITests/).
package xcuitest

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/at-least/ciderui/internal/build"
)

// Device is a simulator's device type: its identifier's last part and its name.
type Device struct {
	Type string
	Name string
}

// IPhone17 is the device a probe taps on unless it names another.
var IPhone17 = Device{Type: "iPhone-17", Name: "iPhone 17"}

// Result is the browser the steps ran in, and whether Safari's tip was there to
// close ("closed", "none").
type Result struct {
	Label string
	Tip   string
}

// @invariant: a command run while the probe's server answers; its output, or an
// error with the output's end
func run(env []string, name string, args ...string) (string, error) {
	cmd := exec.Command(name, args...)
	cmd.Env = env
	var out bytes.Buffer
	cmd.Stdout = &out
	cmd.Stderr = &out
	if err := cmd.Run(); err != nil {
		var exit *exec.ExitError
		if !errors.As(err, &exit) {
			return "", fmt.Errorf("%s: %w", name, err)
		}
		s := out.String()
		if len(s) > 6000 {
			s = s[len(s)-6000:]
		}
		return "", fmt.Errorf("%s %s exited %d:\n%s", name, strings.Join(args, " "), exit.ExitCode(), s)
	}
	return out.String(), nil
}

func xcrun(args ...string) (string, error) { return run(os.Environ(), "xcrun", args...) }

// Taps opens url in Safari on a new simulator of device and takes steps there.
func Taps(url string, steps []string, device Device) (result Result, err error) {
	deviceType := "com.apple.CoreSimulator.SimDeviceType." + device.Type
	out, err := xcrun("simctl", "list", "runtimes", "iOS", "-j")
	if err != nil {
		return Result{}, err
	}
	var list struct {
		Runtimes []struct {
			Identifier           string
			Version              string
			IsAvailable          bool
			SupportedDeviceTypes []struct{ Identifier string }
		}
	}
	if err := json.Unmarshal([]byte(out), &list); err != nil {
		return Result{}, fmt.Errorf("simctl list runtimes: %w", err)
	}
	var runtimeID, version string
	for _, r := range list.Runtimes {
		if !r.IsAvailable {
			continue
		}
		for _, d := range r.SupportedDeviceTypes {
			if d.Identifier == deviceType {
				runtimeID, version = r.Identifier, r.Version
			}
		}
	}
	if runtimeID == "" {
		return Result{}, fmt.Errorf("no iOS runtime has the device type %s", deviceType)
	}
	out, err = xcrun("simctl", "create", "ciderui-tap", deviceType, runtimeID)
	if err != nil {
		return Result{}, err
	}
	udid := strings.TrimSpace(out)
	dir, err := os.MkdirTemp("", "ciderui-tap-")
	if err != nil {
		return Result{}, err
	}
	defer func() {
		if cerr := cleanUp(udid, dir); err == nil {
			err = cerr
		}
	}()
	if _, err := xcrun("simctl", "boot", udid); err != nil {
		return Result{}, err
	}
	if _, err := xcrun("simctl", "bootstatus", udid, "-b"); err != nil {
		return Result{}, err
	}
	if _, err := run(os.Environ(), "xcodegen", "generate", "--spec", filepath.Join(build.Root, "reference", "xcuitest", "project.yml"), "--project", dir); err != nil {
		return Result{}, err
	}
	// @external: TEST_RUNNER_ names reach the test as the names without it
	env := append(os.Environ(), "TEST_RUNNER_TAP_URL="+url, "TEST_RUNNER_TAP_STEPS="+strings.Join(steps, ","))
	log, err := run(env, "xcodebuild", "test", "-project", filepath.Join(dir, "Tap.xcodeproj"), "-scheme", "TapUITests", "-destination", "id="+udid, "-derivedDataPath", filepath.Join(dir, "dd"))
	if err != nil {
		return Result{}, err
	}
	tip := "none"
	if strings.Contains(log, "ciderui-tap: Safari's tip closed") {
		tip = "closed"
	}
	return Result{Label: fmt.Sprintf("Safari %s, iOS %s simulator (%s), XCUITest's taps", version, version, device.Name), Tip: tip}, nil
}

// @invariant: the simulator shut down if it is booted, then deleted, and the temporary
// directory removed, whether or not the steps failed
func cleanUp(udid, dir string) error {
	out, err := xcrun("simctl", "list", "devices", "-j")
	if err != nil {
		return err
	}
	var list struct {
		Devices map[string][]struct {
			UDID  string
			State string
		}
	}
	if err := json.Unmarshal([]byte(out), &list); err != nil {
		return fmt.Errorf("simctl list devices: %w", err)
	}
	for _, ds := range list.Devices {
		for _, d := range ds {
			if d.UDID == udid && d.State == "Booted" {
				if _, err := xcrun("simctl", "shutdown", udid); err != nil {
					return err
				}
			}
		}
	}
	if _, err := xcrun("simctl", "delete", udid); err != nil {
		return err
	}
	return os.RemoveAll(dir)
}
