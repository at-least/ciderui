// @invariant: a results package's head; command is what writes the file
func header(command string) string {
	return "// Code generated by go run ./reference/" + command + "; DO NOT EDIT.\n\npackage results\n\nimport \"github.com/at-least/ciderui/internal/reference\"\n\n"
}

// GoName is a record's name as its Go variable: retail-dark is RetailDark.
func GoName(name string) (string, error) {
	// @invariant: pages.go and its Pages are the registry's
	if name == "pages" {
		return "", fmt.Errorf("record %q: the registry's name", name)
	}
	var b strings.Builder
	for _, part := range strings.FieldsFunc(name, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) }) {
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	s := b.String()
	if s == "" || !unicode.IsUpper(rune(s[0])) {
		return "", fmt.Errorf("record %q has no Go name: it starts with no letter", name)
	}
	return s, nil
}

// @invariant: a string that holds quotes reads as it is, backquoted, where it can be
func quote(s string) string {
	if strings.Contains(s, `"`) && strconv.CanBackquote(s) {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

// @invariant: format's %q are Go string literals, each written by quote; its verbs are
// one letter each, no %%
func emit(b *bytes.Buffer, format string, args ...any) {
	verbs := strings.Split(format, "%")[1:]
	for i, v := range verbs {
		if v[0] == 'q' {
			args[i] = quote(args[i].(string))
		}
	}
	fmt.Fprintf(b, strings.ReplaceAll(format, "%q", "%s"), args...)
}

func float(v float64) string { return strconv.FormatFloat(v, 'g', -1, 64) }

func goStyles(b *bytes.Buffer, field string, list []Style) {
	if list == nil {
		return
	}
	emit(b, "%s: []reference.Style{\n", field)
	for _, s := range list {
		if s.Image == nil {
			emit(b, "{Name: %q, Text: %q},\n", s.Name, s.Text)
			continue
		}
		emit(b, "{Name: %q, Image: &reference.Image{ViewBox: %q, Shapes: []reference.Shape{\n", s.Name, s.Image.ViewBox)
		for _, sh := range s.Image.Shapes {
			emit(b, "{Shape: %q, Fill: %q, Stroke: %q},\n", sh.Shape, sh.Fill, sh.Stroke)
		}
		b.WriteString("}}},\n")
	}
	b.WriteString("},\n")
}

func goProbe(b *bytes.Buffer, p Probe) {
	if p.Missing {
		emit(b, "{Name: %q, Missing: true},\n", p.Name)
		return
	}
	emit(b, "{\nName: %q,\nHTML: %q,\n", p.Name, p.HTML)
	goStyles(b, "Styles", p.Styles)
	if p.States != nil {
		b.WriteString("States: []reference.State{\n")
		for _, s := range p.States {
			emit(b, "{Name: %q, ", s.Name)
			goStyles(b, "Styles", s.Styles)
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	if p.Box != nil {
		emit(b, "Box: &reference.Box{Width: %s, Height: %s", float(p.Box.Width), float(p.Box.Height))
		if p.Box.At != nil {
			emit(b, ", At: &reference.Position{Top: %s, Left: %s}", float(p.Box.At.Top), float(p.Box.At.Left))
		}
		b.WriteString("},\n")
	}
	if p.Keyframes != nil {
		b.WriteString("Keyframes: []reference.Keyframes{\n")
		for _, k := range p.Keyframes {
			emit(b, "{Name: %q, Frames: []reference.Keyframe{\n", k.Name)
			for _, f := range k.Frames {
				emit(b, "{At: %q, Style: %q},\n", f.At, f.Style)
			}
			b.WriteString("}},\n")
		}
		b.WriteString("},\n")
	}
	if p.Animations != nil {
		b.WriteString("Animations: []reference.Animation{\n")
		for _, a := range p.Animations {
			emit(b, "{Kind: %q, What: %q, On: %q, Duration: %s, Delay: %s, Easing: %q, From: %q, To: %q", a.Kind, a.What, a.On, float(a.Duration), float(a.Delay), a.Easing, a.From, a.To)
			if a.Observed != nil {
				emit(b, ", Observed: &reference.Observed{Direction: %q, Seen: %d}", a.Observed.Direction, a.Observed.Seen)
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}
	if p.Matches != nil {
		b.WriteString("Matches: []reference.Match{\n")
		for _, m := range p.Matches {
			emit(b, "{Selector: %q, Matches: %t},\n", m.Selector, m.Matches)
		}
		b.WriteString("},\n")
	}
	if p.Sections != nil {
		b.WriteString("Sections: []reference.Section{\n")
		for _, s := range p.Sections {
			emit(b, "{Name: %q, Rows: %d},\n", s.Name, s.Rows)
		}
		b.WriteString("},\n")
	}
	b.WriteString("},\n")
}

// GoFile is reference/apple.com/results/<p.Name>.go: p as a Page literal named by
// GoName, gofmt'd.
func GoFile(p Page) ([]byte, error) {
	name, err := GoName(p.Name)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString(header("apple.com"))
	emit(&b, "var %s = reference.Page{\nName: %q,\nURL: %q,\nFinalURL: %q,\nBrowser: %q,\nDate: %q,\nWidths: []reference.Width{\n", name, p.Name, p.URL, p.FinalURL, p.Browser, p.Date)
	for _, w := range p.Widths {
		emit(&b, "{Width: %d, Probes: []reference.Probe{\n", w.Width)
		for _, pr := range w.Probes {
			goProbe(&b, pr)
		}
		b.WriteString("}},\n")
	}
	b.WriteString("},\n}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("%s: %w", p.Name, err)
	}
	return out, nil
}

// GoRegistry is reference/<command>/results/pages.go: Pages, every record by its
// name, from the names of the records there, each of type (reference.Page,
// reference.SignedInPage).
func GoRegistry(command, typ string, names []string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header(command))
	emit(&b, "// Pages is every record by its name.\nvar Pages = map[string]%s{\n", typ)
	seen := map[string]string{}
	for _, n := range names {
		g, err := GoName(n)
		if err != nil {
			return nil, err
		}
		if other, ok := seen[g]; ok {
			return nil, fmt.Errorf("records %q and %q are both %s in Go", other, n, g)
		}
		seen[g] = n
		emit(&b, "%q: %s,\n", n, g)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// WriteRecord writes the record v, the page named name, to dir/<name>.go, and dir/
// pages.go from the records dir then holds.
func WriteRecord(dir, name string, v ojson.Value) error {
	page, err := FromJSON(name, v)
	if err != nil {
		return err
	}
	src, err := GoFile(page)
	if err != nil {
		return err
	}
	return writeResult(dir, "apple.com", "reference.Page", name, src)
}

// @invariant: dir/<name>.go is src, and dir/pages.go the registry of every record
// dir then holds
func writeResult(dir, command, typ, name string, src []byte) error {
	if err := os.WriteFile(filepath.Join(dir, name+".go"), src, 0o644); err != nil {
		return err
	}
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return err
	}
	var names []string
	for _, f := range files {
		if n := strings.TrimSuffix(filepath.Base(f), ".go"); n != "pages" && !strings.HasSuffix(n, "_test") {
			names = append(names, n)
		}
	}
	registry, err := GoRegistry(command, typ, names)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "pages.go"), registry, 0o644)
}
