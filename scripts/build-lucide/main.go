// Command build-lucide writes go/lucide/lucide.go, every Lucide icon of the pinned
// lucide-static; with --check it fails where the file is stale.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/at-least/ciderui/internal/build"
	"github.com/at-least/ciderui/internal/pinned"
)

const usage = "usage: go run ./scripts/build-lucide [--check]"

func main() {
	args := os.Args[1:]
	if len(args) > 1 || (len(args) == 1 && args[0] != "--check") {
		fmt.Fprintln(os.Stderr, usage)
		os.Exit(2)
	}
	if err := run(len(args) == 1); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(checking bool) error {
	out := filepath.Join(build.Root, "go/lucide/lucide.go")
	pkg, err := pinned.Lucide()
	if err != nil {
		return err
	}
	text, err := source(pkg)
	if err != nil {
		return fmt.Errorf("build-lucide: %w", err)
	}
	if !checking {
		return os.WriteFile(out, []byte(text), 0o644)
	}
	have, err := os.ReadFile(out)
	if err != nil {
		return err
	}
	if string(have) != text {
		fmt.Println("go/lucide/lucide.go is stale: go run ./scripts/build-lucide")
		os.Exit(1)
	}
	return nil
}

type attribute struct{ key, value string }

// element is one of an icon's elements: its tag and its attributes, in their order.
type element struct {
	tag        string
	attributes []attribute
}

// icon is one entry of icon-nodes.json, in the file's order.
type icon struct {
	name     string
	elements []element
}

var (
	svgFile      = regexp.MustCompile(`(?s)<svg([^>]*)>(.*)</svg>`)
	svgAttribute = regexp.MustCompile(`([a-zA-Z:-]+)="([^"]*)"`)
	selfClosing  = regexp.MustCompile(`\s*/>`)
	between      = regexp.MustCompile(`>\s+<`)
	lucideName   = regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`)
)

type svg struct {
	attributes []attribute
	root       string
	inner      string
}

// file is icons/<name>.svg: its <svg>'s attributes but class, xmlns, width and
// height, and its markup.
func file(pkg, name string) (svg, error) {
	b, err := os.ReadFile(filepath.Join(pkg, "icons", name+".svg"))
	if err != nil {
		return svg{}, err
	}
	m := svgFile.FindSubmatch(b)
	if m == nil {
		return svg{}, fmt.Errorf("icons/%s.svg holds no <svg>", name)
	}
	var s svg
	var root []string
	for _, a := range svgAttribute.FindAllStringSubmatch(string(m[1]), -1) {
		if slices.Contains([]string{"class", "xmlns", "width", "height"}, a[1]) {
			continue
		}
		s.attributes = append(s.attributes, attribute{a[1], a[2]})
		root = append(root, a[1]+`="`+a[2]+`"`)
	}
	s.root = strings.Join(root, " ")
	s.inner = strings.TrimSpace(between.ReplaceAllString(selfClosing.ReplaceAllString(string(m[2]), "/>"), "><"))
	return s, nil
}

func goName(name string) string {
	var b strings.Builder
	for _, p := range strings.Split(name, "-") {
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func source(pkg string) (string, error) {
	var meta struct {
		Version string `json:"version"`
	}
	raw, err := os.ReadFile(filepath.Join(pkg, "package.json"))
	if err != nil {
		return "", err
	}
	if err := json.Unmarshal(raw, &meta); err != nil {
		return "", err
	}
	if meta.Version != pinned.LucideVersion {
		return "", fmt.Errorf("the package holds lucide-static %s, pinned %s", meta.Version, pinned.LucideVersion)
	}
	raw, err = os.ReadFile(filepath.Join(pkg, "icon-nodes.json"))
	if err != nil {
		return "", err
	}
	icons, err := iconNodes(raw)
	if err != nil {
		return "", fmt.Errorf("icon-nodes.json: %w", err)
	}
	first, err := file(pkg, icons[0].name)
	if err != nil {
		return "", err
	}
	var viewBox string
	var paint []string
	for _, a := range first.attributes {
		if a.key == "viewBox" {
			viewBox = a.value
		} else {
			paint = append(paint, a.key+`="`+a.value+`"`)
		}
	}
	var out strings.Builder
	fmt.Fprintf(&out, `// Code generated by scripts/build-lucide from lucide-static %s; DO NOT EDIT.

// Package lucide is every Lucide icon (https://lucide.dev/icons/; under its
// license, the repository's LICENSE-Lucide), by its name in Go's capitals:
// shopping-bag is [ShoppingBag]. Each takes the text's color and size (1em);
// a utility on it sizes it otherwise. In a line of text a page adds inline:
// Tailwind's preflight makes an <svg> a block.
package lucide

import "github.com/at-least/ciderui/go/internal/glyph"

// Icon is the type of a field or parameter that holds an icon; its zero value is none.
type Icon = glyph.Icon

func icon(inner string) Icon {
	return glyph.Lucide("%s", `+"`%s`"+`, inner)
}
`, meta.Version, viewBox, strings.Join(paint, " "))
	seen := map[string]string{}
	for _, ic := range icons {
		if !lucideName.MatchString(ic.name) || ic.name[0] >= '0' && ic.name[0] <= '9' {
			return "", fmt.Errorf("%s: not a Lucide name a Go identifier can carry", ic.name)
		}
		var inner strings.Builder
		for _, el := range ic.elements {
			inner.WriteString("<" + el.tag)
			for _, a := range el.attributes {
				inner.WriteString(" " + a.key + `="` + a.value + `"`)
			}
			inner.WriteString("/>")
		}
		own, err := file(pkg, ic.name)
		if err != nil {
			return "", err
		}
		if own.root != first.root {
			return "", fmt.Errorf("%s: its <svg> carries %s, %s's %s", ic.name, own.root, icons[0].name, first.root)
		}
		if own.inner != inner.String() {
			return "", fmt.Errorf("%s: icon-nodes.json's elements are not icons/%s.svg's:\n%s\n%s", ic.name, ic.name, inner.String(), own.inner)
		}
		if strings.Contains(inner.String(), "`") {
			return "", fmt.Errorf("%s: its markup would end the raw string", ic.name)
		}
		constant := goName(ic.name)
		if other, ok := seen[constant]; ok {
			return "", fmt.Errorf("%s and %s are both %s", ic.name, other, constant)
		}
		seen[constant] = ic.name
		fmt.Fprintf(&out, "\n// %s is [%s](https://lucide.dev/icons/%s).\nvar %s = icon(`%s`)\n", constant, ic.name, ic.name, constant, inner.String())
	}
	return out.String(), nil
}

// iconNodes reads icon-nodes.json in its own order, the icons' and each element's
// attributes': a Go map would sort both.
func iconNodes(raw []byte) ([]icon, error) {
	d := json.NewDecoder(bytes.NewReader(raw))
	if err := delim(d, '{'); err != nil {
		return nil, err
	}
	var icons []icon
	for d.More() {
		name, err := str(d)
		if err != nil {
			return nil, err
		}
		ic := icon{name: name, elements: nil}
		if err := delim(d, '['); err != nil {
			return nil, err
		}
		for d.More() {
			if err := delim(d, '['); err != nil {
				return nil, err
			}
			tag, err := str(d)
			if err != nil {
				return nil, err
			}
			el := element{tag: tag, attributes: nil}
			if err := delim(d, '{'); err != nil {
				return nil, err
			}
			for d.More() {
				k, err := str(d)
				if err != nil {
					return nil, err
				}
				v, err := str(d)
				if err != nil {
					return nil, err
				}
				el.attributes = append(el.attributes, attribute{k, v})
			}
			if err := delim(d, '}'); err != nil {
				return nil, err
			}
			if err := delim(d, ']'); err != nil {
				return nil, err
			}
			ic.elements = append(ic.elements, el)
		}
		if err := delim(d, ']'); err != nil {
			return nil, err
		}
		icons = append(icons, ic)
	}
	if len(icons) == 0 {
		return nil, fmt.Errorf("no icons")
	}
	return icons, delim(d, '}')
}

func delim(d *json.Decoder, want json.Delim) error {
	t, err := d.Token()
	if err != nil {
		return err
	}
	if t != want {
		return fmt.Errorf("%v where %v belongs", t, want)
	}
	return nil
}

func str(d *json.Decoder) (string, error) {
	t, err := d.Token()
	if err != nil {
		return "", err
	}
	s, ok := t.(string)
	if !ok {
		return "", fmt.Errorf("%v where a string belongs", t)
	}
	return s, nil
}
