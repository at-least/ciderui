// taps(url, labels, { device, name }): Safari on an iOS simulator opens url
// and XCUITest taps, one after another, the elements those labels name, each
// a touch of the simulator's screen through its HID, as a finger's (where
// WebDriver's taps never click, ./popover/): after each it waits for the
// page's "reported N", the page's own report of what the tap left, which the
// probe's server keeps. On a simulator of the run's own, the device type
// given (an iPhone 17 unless it says), created on the newest iOS runtime and
// deleted after (the booted ones are others'); its UI test generated by
// XcodeGen from xcuitest/project.yml into a temporary directory. Safari's tip
// over the page on a new simulator is closed first (xcuitest/UITests/).
// Gives { label, tip }: the browser, and whether the tip was there to close.
import { spawn } from 'node:child_process';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

// a command run while the probe's server answers; its output, or an error with it
export const run = (cmd, args, env = process.env) => new Promise((resolve, reject) => {
  const p = spawn(cmd, args, { env, stdio: ['ignore', 'pipe', 'pipe'] });
  let out = '';
  p.stdout.on('data', (d) => { out += d; });
  p.stderr.on('data', (d) => { out += d; });
  p.on('close', (code) => code === 0 ? resolve(out) : reject(new Error(`${cmd} ${args.join(' ')} exited ${code}:\n${out.slice(-6000)}`)));
});

export async function taps(url, labels, { device = 'iPhone-17', name = 'iPhone 17' } = {}) {
  const runtime = JSON.parse(await run('xcrun', ['simctl', 'list', 'runtimes', 'iOS', '-j'])).runtimes.filter(r => r.isAvailable).at(-1);
  const udid = (await run('xcrun', ['simctl', 'create', 'ciderui-tap', `com.apple.CoreSimulator.SimDeviceType.${device}`, runtime.identifier])).trim();
  const dir = mkdtempSync(join(tmpdir(), 'ciderui-tap-'));
  try {
    await run('xcrun', ['simctl', 'boot', udid]);
    await run('xcrun', ['simctl', 'bootstatus', udid, '-b']);
    await run('xcodegen', ['generate', '--spec', fileURLToPath(new URL('./xcuitest/project.yml', import.meta.url)), '--project', dir]);
    // TEST_RUNNER_ names reach the test as the names without it
    const log = await run('xcodebuild', ['test', '-project', join(dir, 'Tap.xcodeproj'), '-scheme', 'TapUITests', '-destination', `id=${udid}`, '-derivedDataPath', join(dir, 'dd')],
      { ...process.env, TEST_RUNNER_TAP_URL: url, TEST_RUNNER_TAP_STEPS: labels.join(',') });
    return {
      label: `Safari ${runtime.version}, iOS ${runtime.version} simulator (${name}), XCUITest's taps`,
      tip: log.includes("ciderui-tap: Safari's tip closed") ? 'closed' : 'none',
    };
  } finally {
    const { devices } = JSON.parse(await run('xcrun', ['simctl', 'list', 'devices', '-j']));
    if (Object.values(devices).flat().find(d => d.udid === udid)?.state === 'Booted') await run('xcrun', ['simctl', 'shutdown', udid]);
    await run('xcrun', ['simctl', 'delete', udid]);
    rmSync(dir, { recursive: true });
  }
}
